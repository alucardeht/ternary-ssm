#!/usr/bin/env python3
"""Convert SPIR-V binary to C header with embedded byte array."""
import sys
import os

def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <input.spv> <output.h>")
        sys.exit(1)

    spv_path = sys.argv[1]
    hdr_path = sys.argv[2]
    name = os.path.splitext(os.path.basename(spv_path))[0]

    with open(spv_path, 'rb') as f:
        data = f.read()

    with open(hdr_path, 'w') as f:
        f.write('/* AUTO-GENERATED by spv_to_header.py — do not edit */\n')
        f.write(f'#ifndef {name.upper()}_SPV_H\n')
        f.write(f'#define {name.upper()}_SPV_H\n\n')
        f.write(f'static const unsigned char {name}_spv[] = {{\n')
        for i, b in enumerate(data):
            f.write(f'0x{b:02x},')
            if (i + 1) % 16 == 0:
                f.write('\n')
        if len(data) % 16 != 0:
            f.write('\n')
        f.write('};\n\n')
        f.write(f'static const unsigned int {name}_spv_len = {len(data)};\n\n')
        f.write(f'#endif /* {name.upper()}_SPV_H */\n')

if __name__ == '__main__':
    main()
