#!/usr/bin/env python3
"""R501 S88 ternary covariance factorization gate.

This CPU diagnostic implements the R501 Quality Paradigm 10 finding:
"Ternary Covariance Factorization (TCF)".

The gate constructs token features whose population covariance is generated by a
sparse ternary basis U and diagonal factor strengths, then estimates whether a
factorized ternary covariance update can preserve the useful covariance while
charging only the active factor support. The positive case must recover the
ternary factors, reconstruct the useful covariance, suppress dense sample noise,
and remain cheaper than a dense covariance update.

Controls exercise the declared kill criteria: a random ternary basis can miss
the covariance, a continuous eigenbasis can reconstruct but violates the ternary
substrate, too few factors can underfit, coherent dense residual covariance can
escape the sparse basis, and a dense active basis can erase the price advantage.

This is a synthetic CPU covariance-factorization diagnostic, not heldout CE
progress, real corpus token efficiency, GPU training-speed evidence, or
production v12 integration.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import numpy as np


SCHEMA = "r501_s88_tcf_gate.v1"
CONDITIONS = (
    "positive",
    "random_basis_fail",
    "nonternary_basis_fail",
    "rank_underfit_fail",
    "dense_residual_fail",
    "dense_cost_fail",
)


@dataclass(frozen=True)
class TrialResult:
    condition: str
    seed: int
    expected_pass: bool
    passed: bool
    identifying_correct: bool
    fail_reason: str | None
    dim: int
    token_count: int
    true_rank: int
    used_rank: int
    active_per_factor: int
    covariance_relative_error: float
    dense_sample_relative_error: float
    covariance_noise_reduction_fraction: float
    energy_capture_fraction: float
    basis_alignment_mean: float
    basis_alignment_min: float
    ternary_pattern_violation_count: int
    coherent_residual_fraction: float
    active_update_fraction: float
    factorization_overhead_ratio: float
    paid_work_ratio: float
    projected_covariance_efficiency_multiplier: float


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--seed", type=int, default=50188)
    parser.add_argument("--seed-count", type=int, default=5)
    parser.add_argument("--dim", type=int, default=48)
    parser.add_argument("--token-count", type=int, default=4096)
    parser.add_argument("--rank", type=int, default=8)
    parser.add_argument("--active-per-factor", type=int, default=5)
    parser.add_argument("--dense-active-per-factor", type=int, default=24)
    parser.add_argument("--residual-noise", type=float, default=0.025)
    parser.add_argument("--dense-residual-strength", type=float, default=0.55)
    parser.add_argument("--factorization-overhead", type=float, default=0.08)
    parser.add_argument("--expensive-factorization-overhead", type=float, default=0.55)
    parser.add_argument("--max-covariance-error", type=float, default=0.12)
    parser.add_argument("--min-energy-capture", type=float, default=0.92)
    parser.add_argument("--min-basis-alignment", type=float, default=0.92)
    parser.add_argument("--min-noise-reduction", type=float, default=0.30)
    parser.add_argument("--max-coherent-residual-fraction", type=float, default=0.08)
    parser.add_argument("--max-paid-work-ratio", type=float, default=0.35)
    parser.add_argument("--min-efficiency-multiplier", type=float, default=2.5)
    return parser.parse_args()


def finite(*values: float) -> bool:
    return all(math.isfinite(value) for value in values)


def normalize_columns(matrix: np.ndarray) -> np.ndarray:
    norms = np.maximum(np.linalg.norm(matrix, axis=0, keepdims=True), 1.0e-30)
    return matrix / norms


def make_sparse_ternary_basis(
    rng: np.random.Generator,
    dim: int,
    rank: int,
    active_per_factor: int,
) -> np.ndarray:
    if rank * active_per_factor > dim:
        raise ValueError("rank * active_per_factor must be <= dim for disjoint factors")
    basis = np.zeros((dim, rank), dtype=np.float64)
    indices = rng.permutation(dim)
    for factor in range(rank):
        start = factor * active_per_factor
        active = indices[start : start + active_per_factor]
        basis[active, factor] = rng.choice(np.array([-1.0, 1.0]), size=active_per_factor)
    return basis


def make_random_ternary_basis(
    rng: np.random.Generator,
    dim: int,
    rank: int,
    active_per_factor: int,
) -> np.ndarray:
    basis = np.zeros((dim, rank), dtype=np.float64)
    for factor in range(rank):
        active = rng.choice(dim, size=active_per_factor, replace=False)
        basis[active, factor] = rng.choice(np.array([-1.0, 1.0]), size=active_per_factor)
    return basis


def covariance_from_basis(basis: np.ndarray, strengths: np.ndarray) -> np.ndarray:
    normalized = normalize_columns(basis)
    return normalized @ np.diag(strengths) @ normalized.T


def sample_tokens(
    rng: np.random.Generator,
    basis: np.ndarray,
    strengths: np.ndarray,
    token_count: int,
    residual_noise: float,
    dense_residual_strength: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    normalized = normalize_columns(basis)
    latents = rng.normal(size=(token_count, strengths.shape[0])) * np.sqrt(strengths)
    tokens = latents @ normalized.T
    population = covariance_from_basis(basis, strengths)
    structured = population.copy()

    if dense_residual_strength > 0.0:
        dense_direction = rng.normal(size=(basis.shape[0], 1))
        projection = normalized @ (normalized.T @ dense_direction)
        dense_direction = dense_direction - projection
        dense_direction /= max(float(np.linalg.norm(dense_direction)), 1.0e-30)
        dense_latent = rng.normal(size=(token_count, 1)) * math.sqrt(dense_residual_strength)
        tokens = tokens + dense_latent @ dense_direction.T
        dense_cov = dense_residual_strength * (dense_direction @ dense_direction.T)
        population = population + dense_cov

    noise = rng.normal(size=tokens.shape) * residual_noise
    tokens = tokens + noise
    population = population + (residual_noise**2) * np.eye(basis.shape[0])
    return tokens, structured, population


def sample_covariance(tokens: np.ndarray) -> np.ndarray:
    centered = tokens - np.mean(tokens, axis=0, keepdims=True)
    return centered.T @ centered / max(tokens.shape[0] - 1, 1)


def ternary_factorize(
    covariance: np.ndarray,
    rank: int,
    active_per_factor: int,
) -> np.ndarray:
    _, eigenvectors = np.linalg.eigh(covariance)
    top = eigenvectors[:, -rank:]
    basis = np.zeros_like(top)
    for factor in range(rank):
        vector = top[:, factor]
        active = np.argsort(np.abs(vector))[-active_per_factor:]
        basis[active, factor] = np.sign(vector[active])
        basis[basis[:, factor] == 0.0, factor] = 0.0
    return basis


def continuous_factorize(covariance: np.ndarray, rank: int) -> np.ndarray:
    _, eigenvectors = np.linalg.eigh(covariance)
    return eigenvectors[:, -rank:]


def fit_factor_covariance(tokens: np.ndarray, basis: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    normalized = normalize_columns(basis)
    factors = tokens @ normalized
    strengths = np.var(factors, axis=0, ddof=1)
    return normalized @ np.diag(strengths) @ normalized.T, strengths


def basis_alignment(true_basis: np.ndarray, estimated_basis: np.ndarray) -> tuple[float, float]:
    true_normalized = normalize_columns(true_basis)
    estimated_normalized = normalize_columns(estimated_basis)
    overlap = np.abs(true_normalized.T @ estimated_normalized)
    best = np.max(overlap, axis=1)
    return float(np.mean(best)), float(np.min(best))


def support_fraction(basis: np.ndarray) -> float:
    support = (np.abs(basis @ basis.T) > 0.0)
    return float(np.mean(support))


def ternary_violation_count(basis: np.ndarray) -> int:
    rounded = np.isclose(basis, -1.0) | np.isclose(basis, 0.0) | np.isclose(basis, 1.0)
    return int(np.size(basis) - np.count_nonzero(rounded))


def first_failure(
    *,
    covariance_relative_error: float,
    energy_capture_fraction: float,
    basis_alignment_min: float,
    covariance_noise_reduction_fraction: float,
    ternary_pattern_violation_count: int,
    coherent_residual_fraction: float,
    paid_work_ratio: float,
    projected_covariance_efficiency_multiplier: float,
    args: argparse.Namespace,
) -> str | None:
    if not finite(
        covariance_relative_error,
        energy_capture_fraction,
        basis_alignment_min,
        covariance_noise_reduction_fraction,
        coherent_residual_fraction,
        paid_work_ratio,
        projected_covariance_efficiency_multiplier,
    ):
        return "nonfinite_metric"
    if ternary_pattern_violation_count != 0:
        return "ternary_basis_violation"
    if paid_work_ratio > args.max_paid_work_ratio:
        return "price_paid_work"
    if projected_covariance_efficiency_multiplier < args.min_efficiency_multiplier:
        return "price_efficiency_multiplier"
    if covariance_relative_error > args.max_covariance_error:
        return "covariance_reconstruction_error"
    if energy_capture_fraction < args.min_energy_capture:
        return "energy_capture"
    if basis_alignment_min < args.min_basis_alignment:
        return "basis_alignment"
    if covariance_noise_reduction_fraction < args.min_noise_reduction:
        return "dense_noise_reduction"
    if coherent_residual_fraction > args.max_coherent_residual_fraction:
        return "coherent_residual_debt"
    return None


def run_trial(args: argparse.Namespace, condition: str, seed: int) -> TrialResult:
    rng = np.random.default_rng(seed)
    true_basis = make_sparse_ternary_basis(
        rng, args.dim, args.rank, args.active_per_factor
    )
    strengths = np.linspace(2.4, 0.9, args.rank)

    dense_residual_strength = (
        args.dense_residual_strength if condition == "dense_residual_fail" else 0.0
    )
    tokens, structured_cov, population_cov = sample_tokens(
        rng,
        true_basis,
        strengths,
        args.token_count,
        args.residual_noise,
        dense_residual_strength,
    )
    sample_cov = sample_covariance(tokens)
    dense_sample_relative_error = float(
        np.linalg.norm(sample_cov - population_cov, ord="fro")
        / max(np.linalg.norm(population_cov, ord="fro"), 1.0e-30)
    )

    used_rank = args.rank
    active_per_factor = args.active_per_factor
    factorization_overhead = args.factorization_overhead

    if condition == "random_basis_fail":
        estimated_basis = make_random_ternary_basis(
            rng, args.dim, args.rank, args.active_per_factor
        )
    elif condition == "nonternary_basis_fail":
        estimated_basis = continuous_factorize(sample_cov, args.rank)
    elif condition == "rank_underfit_fail":
        used_rank = max(1, args.rank // 2)
        estimated_basis = ternary_factorize(sample_cov, used_rank, args.active_per_factor)
    elif condition == "dense_cost_fail":
        active_per_factor = args.dense_active_per_factor
        factorization_overhead = args.expensive_factorization_overhead
        estimated_basis = ternary_factorize(sample_cov, args.rank, active_per_factor)
    else:
        estimated_basis = ternary_factorize(sample_cov, args.rank, args.active_per_factor)

    factor_cov, _ = fit_factor_covariance(tokens, estimated_basis)
    covariance_relative_error = float(
        np.linalg.norm(factor_cov - structured_cov, ord="fro")
        / max(np.linalg.norm(structured_cov, ord="fro"), 1.0e-30)
    )
    factor_error_to_population = float(
        np.linalg.norm(factor_cov - population_cov, ord="fro")
        / max(np.linalg.norm(population_cov, ord="fro"), 1.0e-30)
    )
    covariance_noise_reduction_fraction = float(
        1.0
        - factor_error_to_population / max(dense_sample_relative_error, 1.0e-30)
    )

    energy_capture_fraction = float(
        np.trace(factor_cov @ structured_cov) / max(np.trace(structured_cov @ structured_cov), 1.0e-30)
    )
    energy_capture_fraction = max(0.0, min(energy_capture_fraction, 1.5))
    alignment_mean, alignment_min = basis_alignment(true_basis, estimated_basis)
    coherent_residual_fraction = float(
        max(0.0, np.linalg.norm(population_cov - structured_cov, ord="fro"))
        / max(np.linalg.norm(population_cov, ord="fro"), 1.0e-30)
    )
    active_update_fraction = support_fraction(estimated_basis)
    paid_work_ratio = float(active_update_fraction + factorization_overhead)
    projected_covariance_efficiency_multiplier = float(1.0 / max(paid_work_ratio, 1.0e-30))
    violations = ternary_violation_count(estimated_basis)

    fail_reason = first_failure(
        covariance_relative_error=covariance_relative_error,
        energy_capture_fraction=energy_capture_fraction,
        basis_alignment_min=alignment_min,
        covariance_noise_reduction_fraction=covariance_noise_reduction_fraction,
        ternary_pattern_violation_count=violations,
        coherent_residual_fraction=coherent_residual_fraction,
        paid_work_ratio=paid_work_ratio,
        projected_covariance_efficiency_multiplier=projected_covariance_efficiency_multiplier,
        args=args,
    )
    passed = fail_reason is None
    expected_pass = condition == "positive"

    return TrialResult(
        condition=condition,
        seed=seed,
        expected_pass=expected_pass,
        passed=passed,
        identifying_correct=passed == expected_pass,
        fail_reason=fail_reason,
        dim=args.dim,
        token_count=args.token_count,
        true_rank=args.rank,
        used_rank=used_rank,
        active_per_factor=active_per_factor,
        covariance_relative_error=covariance_relative_error,
        dense_sample_relative_error=dense_sample_relative_error,
        covariance_noise_reduction_fraction=covariance_noise_reduction_fraction,
        energy_capture_fraction=energy_capture_fraction,
        basis_alignment_mean=alignment_mean,
        basis_alignment_min=alignment_min,
        ternary_pattern_violation_count=violations,
        coherent_residual_fraction=coherent_residual_fraction,
        active_update_fraction=active_update_fraction,
        factorization_overhead_ratio=factorization_overhead,
        paid_work_ratio=paid_work_ratio,
        projected_covariance_efficiency_multiplier=projected_covariance_efficiency_multiplier,
    )


def aggregate_condition(results: list[TrialResult]) -> dict[str, Any]:
    fields = (
        "dim",
        "token_count",
        "true_rank",
        "used_rank",
        "active_per_factor",
        "covariance_relative_error",
        "dense_sample_relative_error",
        "covariance_noise_reduction_fraction",
        "energy_capture_fraction",
        "basis_alignment_mean",
        "basis_alignment_min",
        "ternary_pattern_violation_count",
        "coherent_residual_fraction",
        "active_update_fraction",
        "factorization_overhead_ratio",
        "paid_work_ratio",
        "projected_covariance_efficiency_multiplier",
    )
    aggregate: dict[str, Any] = {
        "count": len(results),
        "passed_count": sum(result.passed for result in results),
        "identifying_correct_count": sum(result.identifying_correct for result in results),
        "fail_reasons": sorted({result.fail_reason for result in results if result.fail_reason}),
    }
    for field in fields:
        values = np.array([float(getattr(result, field)) for result in results], dtype=np.float64)
        aggregate[f"{field}_mean"] = float(np.mean(values))
        aggregate[f"{field}_min"] = float(np.min(values))
        aggregate[f"{field}_max"] = float(np.max(values))
    return aggregate


def all_finite(results: list[TrialResult]) -> bool:
    for result in results:
        for value in asdict(result).values():
            if isinstance(value, float) and not math.isfinite(value):
                return False
    return True


def required_checks(results: list[TrialResult], aggregates: dict[str, Any]) -> dict[str, bool]:
    positive = [result for result in results if result.condition == "positive"]
    random_basis = [result for result in results if result.condition == "random_basis_fail"]
    nonternary = [result for result in results if result.condition == "nonternary_basis_fail"]
    underfit = [result for result in results if result.condition == "rank_underfit_fail"]
    dense_residual = [result for result in results if result.condition == "dense_residual_fail"]
    dense_cost = [result for result in results if result.condition == "dense_cost_fail"]
    return {
        "all_metrics_finite": all_finite(results),
        "positive_condition_all_pass": all(result.passed for result in positive),
        "positive_condition_reconstructs_useful_covariance": (
            aggregates["positive"]["covariance_relative_error_max"] <= 0.12
            and aggregates["positive"]["energy_capture_fraction_min"] >= 0.92
            and aggregates["positive"]["basis_alignment_min_min"] >= 0.92
        ),
        "positive_condition_reduces_dense_noise": (
            aggregates["positive"]["covariance_noise_reduction_fraction_min"] >= 0.30
            and aggregates["positive"]["coherent_residual_fraction_max"] <= 0.08
        ),
        "positive_condition_is_ternary_and_priced": (
            aggregates["positive"]["ternary_pattern_violation_count_max"] == 0.0
            and aggregates["positive"]["paid_work_ratio_mean"] <= 0.35
            and aggregates["positive"]["projected_covariance_efficiency_multiplier_mean"] >= 2.5
        ),
        "random_basis_control_all_fail_alignment_or_error": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "basis_alignment" in result.fail_reason
                or "covariance_reconstruction_error" in result.fail_reason
                or "energy_capture" in result.fail_reason
            )
            for result in random_basis
        ),
        "nonternary_control_all_fail_ternary": all(
            (not result.passed)
            and result.fail_reason is not None
            and "ternary_basis_violation" in result.fail_reason
            for result in nonternary
        ),
        "underfit_control_all_fail_energy_or_error": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "energy_capture" in result.fail_reason
                or "covariance_reconstruction_error" in result.fail_reason
                or "basis_alignment" in result.fail_reason
            )
            for result in underfit
        ),
        "dense_residual_control_all_fail_residual_or_noise": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "coherent_residual_debt" in result.fail_reason
                or "dense_noise_reduction" in result.fail_reason
                or "covariance_reconstruction_error" in result.fail_reason
            )
            for result in dense_residual
        ),
        "dense_cost_control_all_fail_price": all(
            (not result.passed)
            and result.fail_reason is not None
            and "price" in result.fail_reason
            for result in dense_cost
        ),
        "all_conditions_identified": all(result.identifying_correct for result in results),
    }


def main() -> int:
    args = parse_args()
    results: list[TrialResult] = []
    for condition in CONDITIONS:
        for offset in range(args.seed_count):
            results.append(run_trial(args, condition, args.seed + offset))

    aggregates = {
        condition: aggregate_condition(
            [result for result in results if result.condition == condition]
        )
        for condition in CONDITIONS
    }
    checks = required_checks(results, aggregates)
    decision = "PASS_R501_S88_TCF_GATE" if all(checks.values()) else "FAIL_R501_S88_TCF_GATE"
    payload = {
        "schema": SCHEMA,
        "args": vars(args) | {"output": str(args.output)},
        "conditions": list(CONDITIONS),
        "decision": decision,
        "required_checks": checks,
        "aggregates": aggregates,
        "trials": [asdict(result) for result in results],
        "claim_boundary": (
            "Synthetic CPU ternary covariance factorization gate only; not "
            "heldout CE progress, not real corpus token efficiency, not GPU "
            "training speed, and not production v12 integration."
        ),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")

    positive = aggregates["positive"]
    print(
        "[R501_S88_TCF_GATE] "
        "active=1 "
        f"decision={decision} "
        "disposition=synthetic_positive_control_identified_not_training_speed_claim "
        f"positive_covariance_relative_error_max={positive['covariance_relative_error_max']:.6f} "
        f"positive_energy_capture_fraction_min={positive['energy_capture_fraction_min']:.6f} "
        f"positive_basis_alignment_min={positive['basis_alignment_min_min']:.6f} "
        f"positive_covariance_noise_reduction_fraction_min={positive['covariance_noise_reduction_fraction_min']:.6f} "
        f"positive_active_update_fraction_mean={positive['active_update_fraction_mean']:.6f} "
        f"positive_paid_work_ratio_mean={positive['paid_work_ratio_mean']:.6f} "
        f"positive_projected_covariance_efficiency_multiplier_mean={positive['projected_covariance_efficiency_multiplier_mean']:.6f} "
        f"seed_count={args.seed_count} "
        f"output={args.output}"
    )
    return 0 if decision.startswith("PASS_") else 1


if __name__ == "__main__":
    raise SystemExit(main())
