#!/usr/bin/env python3
"""Run the R437 Adjoint-State Quotient Integrator trace gate.

This is a synthetic, CPU-only diagnostic gate. It does not train a model and it
does not claim real training speed. The gate checks whether the ASQI mechanism
can identify the condition it is supposed to exploit: recurrent cotangent mass
that is generated by forward-owned state features and can therefore be replaced
before dense recurrent backward is paid.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import numpy as np


CONDITIONS = ("positive", "residual_fail", "pricing_fail", "random_control")


@dataclass(frozen=True)
class TrialResult:
    condition: str
    seed: int
    expected_pass: bool
    passed: bool
    identifying_correct: bool
    fail_reason: str | None
    calibration_residual_fraction: float
    heldout_residual_fraction: float
    priced_route_ratio: float
    projected_speedup_if_promoted: float
    accepted_cotangent_mass_fraction: float
    route_components: dict[str, float]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--seed", type=int, default=43700)
    parser.add_argument("--seed-count", type=int, default=5)
    parser.add_argument("--trace-steps", type=int, default=192)
    parser.add_argument("--state-dim", type=int, default=32)
    parser.add_argument("--feature-dim", type=int, default=10)
    parser.add_argument("--basis-rank", type=int, default=4)
    parser.add_argument("--calibration-fraction", type=float, default=0.50)
    parser.add_argument("--ridge", type=float, default=1.0e-5)
    parser.add_argument("--max-weak-residual", type=float, default=0.20)
    parser.add_argument("--max-promotion-residual", type=float, default=0.10)
    parser.add_argument("--max-priced-route", type=float, default=0.90)
    parser.add_argument("--basis-overhead", type=float, default=0.12)
    parser.add_argument("--coefficient-overhead", type=float, default=0.07)
    parser.add_argument("--audit-overhead", type=float, default=0.05)
    parser.add_argument("--memory-overhead", type=float, default=0.02)
    parser.add_argument("--residual-replay-multiplier", type=float, default=1.00)
    parser.add_argument("--pricing-fail-extra-overhead", type=float, default=0.86)
    return parser.parse_args()


def forward_owned_features(
    rng: np.random.Generator,
    trace_steps: int,
    feature_dim: int,
) -> np.ndarray:
    t = np.arange(trace_steps, dtype=np.float64)
    phase = (t + rng.uniform(0.0, 1.0)) / max(1.0, float(trace_steps - 1))
    columns = [
        np.ones_like(phase),
        phase,
        phase * phase,
        np.sin(2.0 * math.pi * phase),
        np.cos(2.0 * math.pi * phase),
        np.sin(6.0 * math.pi * phase),
        np.cos(6.0 * math.pi * phase),
    ]
    while len(columns) < feature_dim:
        freq = float(len(columns) + 1)
        columns.append(np.sin(freq * math.pi * phase + rng.uniform(-0.2, 0.2)))
    x = np.stack(columns[:feature_dim], axis=1)
    x += 0.015 * rng.normal(size=x.shape)
    x[:, 0] = 1.0
    scale = np.maximum(np.std(x, axis=0, keepdims=True), 1.0e-8)
    x = (x - np.mean(x, axis=0, keepdims=True)) / scale
    x[:, 0] = 1.0
    return x


def low_rank_cotangent(
    rng: np.random.Generator,
    features: np.ndarray,
    state_dim: int,
    basis_rank: int,
) -> np.ndarray:
    feature_basis = rng.normal(scale=0.55, size=(features.shape[1], basis_rank))
    state_basis = rng.normal(scale=0.75, size=(basis_rank, state_dim))
    coefficients = features @ feature_basis
    signal = coefficients @ state_basis
    return signal + 0.025 * rng.normal(size=signal.shape)


def cotangent_trace(
    condition: str,
    rng: np.random.Generator,
    features: np.ndarray,
    state_dim: int,
    basis_rank: int,
) -> np.ndarray:
    signal = low_rank_cotangent(rng, features, state_dim, basis_rank)
    if condition in ("positive", "pricing_fail"):
        return signal
    if condition == "residual_fail":
        independent = rng.normal(scale=np.std(signal), size=signal.shape)
        return 0.12 * signal + independent
    if condition == "random_control":
        permuted = np.array(signal, copy=True)
        rng.shuffle(permuted, axis=0)
        return permuted + 0.35 * rng.normal(scale=np.std(signal), size=signal.shape)
    raise ValueError(f"unknown condition: {condition}")


def ridge_fit_predict(
    x_cal: np.ndarray,
    y_cal: np.ndarray,
    x_eval: np.ndarray,
    ridge: float,
) -> np.ndarray:
    lhs = x_cal.T @ x_cal
    lhs += ridge * np.eye(lhs.shape[0], dtype=np.float64)
    rhs = x_cal.T @ y_cal
    weights = np.linalg.solve(lhs, rhs)
    return x_eval @ weights


def residual_fraction(y: np.ndarray, y_hat: np.ndarray) -> float:
    denom = float(np.sum(y * y))
    if denom <= 0.0:
        return math.inf
    return float(np.sum((y - y_hat) ** 2) / denom)


def route_price(args: argparse.Namespace, condition: str, residual: float) -> dict[str, float]:
    extra = args.pricing_fail_extra_overhead if condition == "pricing_fail" else 0.0
    return {
        "basis_overhead": float(args.basis_overhead),
        "coefficient_overhead": float(args.coefficient_overhead),
        "audit_overhead": float(args.audit_overhead),
        "memory_overhead": float(args.memory_overhead),
        "residual_replay": float(residual * args.residual_replay_multiplier),
        "pricing_fail_extra_overhead": float(extra),
    }


def run_trial(args: argparse.Namespace, condition: str, seed: int) -> TrialResult:
    rng = np.random.default_rng(seed)
    features = forward_owned_features(rng, args.trace_steps, args.feature_dim)
    cotangent = cotangent_trace(condition, rng, features, args.state_dim, args.basis_rank)

    split = int(round(args.trace_steps * args.calibration_fraction))
    split = max(args.feature_dim + 2, min(args.trace_steps - 2, split))
    x_cal, x_hold = features[:split], features[split:]
    y_cal, y_hold = cotangent[:split], cotangent[split:]

    y_cal_hat = ridge_fit_predict(x_cal, y_cal, x_cal, args.ridge)
    y_hold_hat = ridge_fit_predict(x_cal, y_cal, x_hold, args.ridge)
    calibration_residual = residual_fraction(y_cal, y_cal_hat)
    heldout_residual = residual_fraction(y_hold, y_hold_hat)
    components = route_price(args, condition, heldout_residual)
    priced_route = float(sum(components.values()))
    projected_speedup = 1.0 / priced_route if priced_route > 0.0 else math.inf

    residual_pass = heldout_residual <= args.max_weak_residual
    promotion_pass = heldout_residual <= args.max_promotion_residual
    price_pass = priced_route < args.max_priced_route
    passed = bool(residual_pass and promotion_pass and price_pass)
    expected_pass = condition == "positive"
    identifying_correct = passed == expected_pass

    fail_reason = None
    if not passed:
        if not residual_pass:
            fail_reason = "heldout_residual_above_weak_gate"
        elif not promotion_pass:
            fail_reason = "heldout_residual_above_promotion_gate"
        elif not price_pass:
            fail_reason = "priced_route_not_below_dense_backward_budget"

    return TrialResult(
        condition=condition,
        seed=seed,
        expected_pass=expected_pass,
        passed=passed,
        identifying_correct=identifying_correct,
        fail_reason=fail_reason,
        calibration_residual_fraction=calibration_residual,
        heldout_residual_fraction=heldout_residual,
        priced_route_ratio=priced_route,
        projected_speedup_if_promoted=projected_speedup,
        accepted_cotangent_mass_fraction=max(0.0, 1.0 - heldout_residual),
        route_components=components,
    )


def finite_trial(trial: TrialResult) -> bool:
    values = (
        trial.calibration_residual_fraction,
        trial.heldout_residual_fraction,
        trial.priced_route_ratio,
        trial.projected_speedup_if_promoted,
        trial.accepted_cotangent_mass_fraction,
    )
    return all(math.isfinite(float(value)) for value in values)


def aggregate(trials: list[TrialResult]) -> dict[str, dict[str, float]]:
    grouped: dict[str, list[TrialResult]] = {}
    for trial in trials:
        grouped.setdefault(trial.condition, []).append(trial)

    out: dict[str, dict[str, float]] = {}
    for condition, rows in grouped.items():
        residuals = np.array([row.heldout_residual_fraction for row in rows], dtype=np.float64)
        prices = np.array([row.priced_route_ratio for row in rows], dtype=np.float64)
        speedups = np.array([row.projected_speedup_if_promoted for row in rows], dtype=np.float64)
        out[condition] = {
            "count": float(len(rows)),
            "pass_count": float(sum(row.passed for row in rows)),
            "heldout_residual_min": float(np.min(residuals)),
            "heldout_residual_mean": float(np.mean(residuals)),
            "heldout_residual_max": float(np.max(residuals)),
            "priced_route_mean": float(np.mean(prices)),
            "projected_speedup_mean": float(np.mean(speedups)),
        }
    return out


def main() -> int:
    args = parse_args()
    if args.seed_count < 1:
        raise ValueError("--seed-count must be at least 1")

    trials: list[TrialResult] = []
    for seed_offset in range(args.seed_count):
        seed = args.seed + seed_offset
        for condition in CONDITIONS:
            trials.append(run_trial(args, condition, seed))

    required_passes = {
        "all_metrics_finite": all(finite_trial(trial) for trial in trials),
        "positive_condition_all_pass": all(
            trial.passed for trial in trials if trial.condition == "positive"
        ),
        "positive_condition_all_promotion_residual": all(
            trial.heldout_residual_fraction <= args.max_promotion_residual
            for trial in trials
            if trial.condition == "positive"
        ),
        "positive_condition_all_priced_route": all(
            trial.priced_route_ratio < args.max_priced_route
            for trial in trials
            if trial.condition == "positive"
        ),
        "residual_fail_control_all_fail": all(
            not trial.passed
            and trial.fail_reason == "heldout_residual_above_weak_gate"
            for trial in trials
            if trial.condition == "residual_fail"
        ),
        "pricing_fail_control_all_fail": all(
            not trial.passed
            and trial.fail_reason == "priced_route_not_below_dense_backward_budget"
            for trial in trials
            if trial.condition == "pricing_fail"
        ),
        "random_control_all_fail": all(
            not trial.passed for trial in trials if trial.condition == "random_control"
        ),
        "all_conditions_identified": all(trial.identifying_correct for trial in trials),
    }

    decision = (
        "PASS_R437_ASQI_TRACE_GATE"
        if all(required_passes.values())
        else "FAIL_R437_ASQI_TRACE_GATE"
    )
    disposition = (
        "synthetic_positive_control_identified_not_training_speed_claim"
        if decision.startswith("PASS_")
        else "asqi_trace_gate_failed_or_non_identifying"
    )
    result: dict[str, Any] = {
        "decision": decision,
        "disposition": disposition,
        "claim_scope": (
            "CPU synthetic ASQI trace gate. It verifies whether forward-owned "
            "features can reconstruct heldout recurrent cotangents under a "
            "priced route before dense backward. It is not a measured "
            "heldout-progress training speedup."
        ),
        "condition_under_test": (
            "Speed is expected only in the positive condition, where the exact "
            "dense recurrent cotangent is mostly generated by forward-owned "
            "state features. The controls prove the gate fails when residual "
            "mass is not forward-owned or pricing exceeds dense backward."
        ),
        "thresholds": {
            "max_weak_residual": args.max_weak_residual,
            "max_promotion_residual": args.max_promotion_residual,
            "max_priced_route": args.max_priced_route,
            "required_projected_speedup_over_dense_backward": 1.0 / args.max_priced_route,
        },
        "shape": {
            "seed": args.seed,
            "seed_count": args.seed_count,
            "trace_steps": args.trace_steps,
            "state_dim": args.state_dim,
            "feature_dim": args.feature_dim,
            "basis_rank": args.basis_rank,
            "calibration_fraction": args.calibration_fraction,
        },
        "route_defaults": {
            "basis_overhead": args.basis_overhead,
            "coefficient_overhead": args.coefficient_overhead,
            "audit_overhead": args.audit_overhead,
            "memory_overhead": args.memory_overhead,
            "residual_replay_multiplier": args.residual_replay_multiplier,
            "pricing_fail_extra_overhead": args.pricing_fail_extra_overhead,
        },
        "required_passes": required_passes,
        "aggregate": aggregate(trials),
        "trials": [asdict(trial) for trial in trials],
    }

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    positive = result["aggregate"]["positive"]
    print(
        "[R437_ASQI_TRACE_GATE] "
        f"decision={decision} disposition={disposition} "
        f"positive_residual_mean={positive['heldout_residual_mean']:.6f} "
        f"positive_priced_route_mean={positive['priced_route_mean']:.6f} "
        f"positive_projected_speedup_mean={positive['projected_speedup_mean']:.6f} "
        f"seed_count={args.seed_count} output={args.output}"
    )
    return 0 if decision.startswith("PASS_") else 1


if __name__ == "__main__":
    raise SystemExit(main())
