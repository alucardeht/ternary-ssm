#!/usr/bin/env python3
"""R502 S15 adjoint-state Krylov projection gate.

This CPU diagnostic implements the R502 Speed finding:
"Adjoint-State Krylov Projection".

The gate builds synthetic recurrent cotangent traces whose exact adjoints are
mostly contained in a low-dimensional Krylov subspace generated by repeated
applications of A^T to the local CE state gradient. It projects exact adjoints
onto that subspace, measures residual energy on train and held-out traces, and
prices the coefficient update plus residual audit against dense recurrent BPTT.

Controls exercise the declared risks: the adjoint can have too much orthogonal
energy, the required Krylov rank can erase the speed denominator, a stale basis
can miss the trace, the Krylov basis can become ill-conditioned, and the audit
cost can exceed the saved backward work.

This is a synthetic CPU Krylov-projection diagnostic, not heldout CE progress,
real corpus token efficiency, GPU training-speed evidence, or production v12
integration.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import numpy as np


SCHEMA = "r502_s15_adjoint_krylov_gate.v1"
CONDITIONS = (
    "positive",
    "residual_energy_fail",
    "rank_too_high_fail",
    "stale_basis_fail",
    "ill_conditioned_basis_fail",
    "audit_cost_fail",
)


@dataclass(frozen=True)
class TrialResult:
    condition: str
    seed: int
    expected_pass: bool
    passed: bool
    identifying_correct: bool
    fail_reason: str | None
    state_dim: int
    krylov_dim: int
    effective_rank: int
    residual_energy_fraction: float
    heldout_residual_energy_fraction: float
    descent_cosine: float
    heldout_descent_cosine: float
    basis_condition_proxy: float
    priced_work_ratio: float
    projected_speedup: float


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--seed", type=int, default=50215)
    parser.add_argument("--seed-count", type=int, default=5)
    parser.add_argument("--state-dim", type=int, default=64)
    parser.add_argument("--krylov-dim", type=int, default=8)
    parser.add_argument("--high-krylov-dim", type=int, default=56)
    parser.add_argument("--noise-scale", type=float, default=0.018)
    parser.add_argument("--bad-noise-scale", type=float, default=0.55)
    parser.add_argument("--coefficient-overhead-ratio", type=float, default=0.05)
    parser.add_argument("--audit-overhead-ratio", type=float, default=0.08)
    parser.add_argument("--expensive-audit-overhead-ratio", type=float, default=0.86)
    parser.add_argument("--max-residual-energy-fraction", type=float, default=0.10)
    parser.add_argument("--min-descent-cosine", type=float, default=0.95)
    parser.add_argument("--max-priced-work-ratio", type=float, default=0.90)
    parser.add_argument("--max-basis-condition-proxy", type=float, default=1.0e6)
    return parser.parse_args()


def finite(*values: float) -> bool:
    return all(math.isfinite(value) for value in values)


def cosine(a: np.ndarray, b: np.ndarray) -> float:
    denom = max(float(np.linalg.norm(a) * np.linalg.norm(b)), 1.0e-30)
    return float(np.dot(a, b) / denom)


def make_transition(args: argparse.Namespace, rng: np.random.Generator, condition: str) -> np.ndarray:
    if condition == "ill_conditioned_basis_fail":
        return np.eye(args.state_dim, dtype=np.float64)
    q, _ = np.linalg.qr(rng.normal(size=(args.state_dim, args.state_dim)))
    eigs = np.linspace(0.96, 0.25, args.state_dim)
    return q @ np.diag(eigs) @ q.T


def krylov_basis(a_t: np.ndarray, grad: np.ndarray, krylov_dim: int) -> tuple[np.ndarray, int, float]:
    vectors = []
    current = grad.astype(np.float64)
    for _ in range(krylov_dim):
        vectors.append(current.copy())
        current = a_t @ current
    matrix = np.stack(vectors, axis=1)
    q, r = np.linalg.qr(matrix, mode="reduced")
    diag = np.abs(np.diag(r))
    threshold = max(float(np.max(diag)), 1.0) * 1.0e-10
    effective_rank = int(np.sum(diag > threshold))
    if effective_rank == 0:
        condition_proxy = 1.0e12
    else:
        safe_diag = diag[:effective_rank]
        condition_proxy = float(np.max(safe_diag) / max(float(np.min(safe_diag)), 1.0e-30))
    return q[:, : max(effective_rank, 1)], effective_rank, condition_proxy


def orthogonal_noise(rng: np.random.Generator, basis: np.ndarray, scale: float) -> np.ndarray:
    noise = rng.normal(size=basis.shape[0])
    noise = noise - basis @ (basis.T @ noise)
    norm = max(float(np.linalg.norm(noise)), 1.0e-30)
    return scale * noise / norm


def make_adjoint(
    rng: np.random.Generator,
    basis: np.ndarray,
    condition: str,
    noise_scale: float,
) -> np.ndarray:
    coeff = rng.normal(size=basis.shape[1])
    in_space = basis @ coeff
    scale = np.linalg.norm(in_space)
    noise = orthogonal_noise(rng, basis, noise_scale * max(float(scale), 1.0))
    if condition == "residual_energy_fail":
        noise = orthogonal_noise(rng, basis, 0.95 * max(float(scale), 1.0))
    return in_space + noise


def project_metrics(basis: np.ndarray, adjoint: np.ndarray) -> tuple[float, float, np.ndarray]:
    projected = basis @ (basis.T @ adjoint)
    residual = adjoint - projected
    residual_fraction = float(
        np.dot(residual, residual) / max(float(np.dot(adjoint, adjoint)), 1.0e-30)
    )
    return residual_fraction, cosine(projected, adjoint), projected


def run_trial(args: argparse.Namespace, condition: str, seed: int) -> TrialResult:
    rng = np.random.default_rng(seed)
    krylov_dim = args.high_krylov_dim if condition == "rank_too_high_fail" else args.krylov_dim
    a = make_transition(args, rng, condition)
    grad = rng.normal(size=args.state_dim)
    basis, effective_rank, condition_proxy = krylov_basis(a.T, grad, krylov_dim)

    if condition == "stale_basis_fail":
        stale_grad = rng.normal(size=args.state_dim)
        basis_for_projection, effective_rank, condition_proxy = krylov_basis(a.T, stale_grad, krylov_dim)
        basis_for_adjoint = basis
    else:
        basis_for_projection = basis
        basis_for_adjoint = basis

    noise_scale = args.bad_noise_scale if condition == "residual_energy_fail" else args.noise_scale
    adjoint = make_adjoint(rng, basis_for_adjoint, condition, noise_scale)
    heldout_adjoint = make_adjoint(rng, basis_for_adjoint, condition, noise_scale * 1.15)
    residual_fraction, descent_cosine, _ = project_metrics(basis_for_projection, adjoint)
    heldout_residual_fraction, heldout_descent_cosine, _ = project_metrics(
        basis_for_projection,
        heldout_adjoint,
    )

    audit_overhead = (
        args.expensive_audit_overhead_ratio
        if condition == "audit_cost_fail"
        else args.audit_overhead_ratio
    )
    priced_work_ratio = (
        krylov_dim / args.state_dim
        + args.coefficient_overhead_ratio
        + audit_overhead
    )
    projected_speedup = 1.0 / priced_work_ratio

    failed: list[str] = []
    if not finite(
        residual_fraction,
        heldout_residual_fraction,
        descent_cosine,
        heldout_descent_cosine,
        condition_proxy,
        priced_work_ratio,
        projected_speedup,
    ):
        failed.append("non_finite_metric")
    if effective_rank < krylov_dim:
        failed.append("rank_deficient_basis")
    if condition_proxy > args.max_basis_condition_proxy:
        failed.append("ill_conditioned_basis")
    if residual_fraction > args.max_residual_energy_fraction:
        failed.append("residual_energy")
    if heldout_residual_fraction > args.max_residual_energy_fraction:
        failed.append("heldout_residual_energy")
    if descent_cosine < args.min_descent_cosine or heldout_descent_cosine < args.min_descent_cosine:
        failed.append("descent_alignment")
    if priced_work_ratio > args.max_priced_work_ratio:
        failed.append("priced_work")

    expected_pass = condition == "positive"
    passed = not failed
    return TrialResult(
        condition=condition,
        seed=seed,
        expected_pass=expected_pass,
        passed=passed,
        identifying_correct=passed == expected_pass,
        fail_reason=";".join(failed) if failed else None,
        state_dim=args.state_dim,
        krylov_dim=krylov_dim,
        effective_rank=effective_rank,
        residual_energy_fraction=residual_fraction,
        heldout_residual_energy_fraction=heldout_residual_fraction,
        descent_cosine=descent_cosine,
        heldout_descent_cosine=heldout_descent_cosine,
        basis_condition_proxy=condition_proxy,
        priced_work_ratio=priced_work_ratio,
        projected_speedup=projected_speedup,
    )


def aggregate_condition(results: list[TrialResult]) -> dict[str, Any]:
    fields = (
        "state_dim",
        "krylov_dim",
        "effective_rank",
        "residual_energy_fraction",
        "heldout_residual_energy_fraction",
        "descent_cosine",
        "heldout_descent_cosine",
        "basis_condition_proxy",
        "priced_work_ratio",
        "projected_speedup",
    )
    aggregate: dict[str, Any] = {
        "count": len(results),
        "passed_count": sum(result.passed for result in results),
        "identifying_correct_count": sum(result.identifying_correct for result in results),
        "fail_reasons": sorted({result.fail_reason for result in results if result.fail_reason}),
    }
    for field in fields:
        values = np.array([float(getattr(result, field)) for result in results], dtype=np.float64)
        aggregate[f"{field}_mean"] = float(np.mean(values))
        aggregate[f"{field}_min"] = float(np.min(values))
        aggregate[f"{field}_max"] = float(np.max(values))
    return aggregate


def all_finite(results: list[TrialResult]) -> bool:
    for result in results:
        for value in asdict(result).values():
            if isinstance(value, float) and not math.isfinite(value):
                return False
    return True


def required_checks(results: list[TrialResult], aggregates: dict[str, Any]) -> dict[str, bool]:
    positive = [result for result in results if result.condition == "positive"]
    residual = [result for result in results if result.condition == "residual_energy_fail"]
    rank = [result for result in results if result.condition == "rank_too_high_fail"]
    stale = [result for result in results if result.condition == "stale_basis_fail"]
    ill = [result for result in results if result.condition == "ill_conditioned_basis_fail"]
    audit = [result for result in results if result.condition == "audit_cost_fail"]
    return {
        "all_metrics_finite": all_finite(results),
        "positive_condition_all_pass": all(result.passed for result in positive),
        "positive_condition_residual_energy_bounded": (
            aggregates["positive"]["residual_energy_fraction_max"] <= 0.10
            and aggregates["positive"]["heldout_residual_energy_fraction_max"] <= 0.10
            and aggregates["positive"]["descent_cosine_min"] >= 0.95
        ),
        "positive_condition_cost_and_rank_priced": (
            aggregates["positive"]["priced_work_ratio_mean"] < 0.90
            and aggregates["positive"]["effective_rank_min"] == aggregates["positive"]["krylov_dim_min"]
            and aggregates["positive"]["basis_condition_proxy_max"] <= 1.0e6
        ),
        "residual_control_all_fail_residual": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "residual_energy" in result.fail_reason
                or "heldout_residual_energy" in result.fail_reason
            )
            for result in residual
        ),
        "rank_control_all_fail_priced_work": all(
            (not result.passed)
            and result.fail_reason is not None
            and "priced_work" in result.fail_reason
            for result in rank
        ),
        "stale_basis_control_all_fail_residual": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "residual_energy" in result.fail_reason
                or "heldout_residual_energy" in result.fail_reason
                or "descent_alignment" in result.fail_reason
            )
            for result in stale
        ),
        "ill_conditioned_control_all_fail_rank_or_condition": all(
            (not result.passed)
            and result.fail_reason is not None
            and (
                "rank_deficient_basis" in result.fail_reason
                or "ill_conditioned_basis" in result.fail_reason
            )
            for result in ill
        ),
        "audit_cost_control_all_fail_priced_work": all(
            (not result.passed)
            and result.fail_reason is not None
            and "priced_work" in result.fail_reason
            for result in audit
        ),
        "all_conditions_identified": all(result.identifying_correct for result in results),
    }


def main() -> int:
    args = parse_args()
    if args.seed_count < 1:
        raise ValueError("--seed-count must be at least 1")
    if args.state_dim < 2:
        raise ValueError("--state-dim must be at least 2")
    if not 1 <= args.krylov_dim <= args.state_dim:
        raise ValueError("--krylov-dim must be in [1, state_dim]")
    if not 1 <= args.high_krylov_dim <= args.state_dim:
        raise ValueError("--high-krylov-dim must be in [1, state_dim]")

    results: list[TrialResult] = []
    for condition in CONDITIONS:
        for offset in range(args.seed_count):
            results.append(run_trial(args, condition, args.seed + offset))

    aggregates = {
        condition: aggregate_condition(
            [result for result in results if result.condition == condition]
        )
        for condition in CONDITIONS
    }
    checks = required_checks(results, aggregates)
    decision = "PASS_R502_S15_ADJOINT_KRYLOV_GATE" if all(checks.values()) else "FAIL_R502_S15_ADJOINT_KRYLOV_GATE"
    payload = {
        "schema": SCHEMA,
        "args": vars(args) | {"output": str(args.output)},
        "conditions": list(CONDITIONS),
        "decision": decision,
        "required_checks": checks,
        "aggregates": aggregates,
        "trials": [asdict(result) for result in results],
        "claim_boundary": (
            "Synthetic CPU adjoint-state Krylov projection gate only; not "
            "heldout CE progress, not real corpus token efficiency, not GPU "
            "training speed, and not production v12 integration."
        ),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")

    positive = aggregates["positive"]
    print(
        "[R502_S15_ADJOINT_KRYLOV_GATE] "
        "active=1 "
        f"decision={decision} "
        "disposition=synthetic_positive_control_identified_not_training_speed_claim "
        f"positive_krylov_dim_mean={positive['krylov_dim_mean']:.6f} "
        f"positive_residual_energy_fraction_max={positive['residual_energy_fraction_max']:.12e} "
        f"positive_heldout_residual_energy_fraction_max={positive['heldout_residual_energy_fraction_max']:.12e} "
        f"positive_descent_cosine_min={positive['descent_cosine_min']:.12e} "
        f"positive_priced_work_ratio_mean={positive['priced_work_ratio_mean']:.6f} "
        f"positive_projected_speedup_mean={positive['projected_speedup_mean']:.6f} "
        f"seed_count={args.seed_count} "
        f"output={args.output}"
    )
    return 0 if decision.startswith("PASS_") else 1


if __name__ == "__main__":
    raise SystemExit(main())
